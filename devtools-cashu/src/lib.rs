//! Shared by the golden generator and the cross-checks: a test mint run on the `cashu` crate's own
//! mint-side functions, and spends built twice, as `fps-protocol` wire requests for
//! `fps-cashu-core` and as `cashu` requests for the crate's own checks.

use bitcoin::bip32::Xpriv;
use bitcoin::secp256k1::{self, Secp256k1};
use bitcoin::NetworkKind;
use cashu::dhke;
use cashu::nuts::nut02::KeySetVersion;
use cashu::nuts::{
    BlindSignature, BlindedMessage, CurrencyUnit, Id, Keys, MeltRequest, MintKeySet, P2PKWitness,
    Proof, SpendingConditionVerification, SwapRequest, Witness,
};
use cashu::secret::Secret;
use cashu::{Amount, PublicKey, SecretKey};
use fps_cashu_core::keys::PhoneMintKeys;
use fps_protocol::{
    ByteBuf, CashuDleq, CashuInput, CashuKey, CashuKeyset, CashuMintDescriptor, CashuOpening,
    CashuOutput, CashuOutputHint, CashuSignRequest, CashuSpendKind, FixedBytes,
};
use rand::RngCore;

/// The amounts of a full sat keyset: every power of two up to 2^31, as testnut publishes.
pub fn standard_amounts() -> Vec<u64> {
    (0..32).map(|bit| 1u64 << bit).collect()
}

/// One keyset of a test mint, generated by `MintKeySet::generate` from a seed.
pub struct TestKeyset {
    pub keyset: MintKeySet,
    pub active: bool,
}

impl TestKeyset {
    pub fn generate(
        seed: &[u8],
        amounts: &[u64],
        input_fee_ppk: u64,
        final_expiry: Option<u64>,
        version: KeySetVersion,
        active: bool,
    ) -> Self {
        let xpriv = Xpriv::new_master(NetworkKind::Main, seed).expect("seed is valid");
        let keyset = MintKeySet::generate(
            &Secp256k1::new(),
            xpriv,
            CurrencyUnit::Sat,
            amounts,
            input_fee_ppk,
            final_expiry,
            version,
        );
        Self { keyset, active }
    }

    pub fn id(&self) -> Id {
        self.keyset.id
    }

    pub fn id_bytes(&self) -> Vec<u8> {
        self.keyset.id.to_bytes()
    }

    pub fn keys(&self) -> Keys {
        Keys::from(self.keyset.keys.clone())
    }

    /// The keyset as a mint descriptor carries it.
    pub fn wire(&self) -> CashuKeyset {
        CashuKeyset {
            id: ByteBuf(self.id_bytes()),
            unit: "sat".to_owned(),
            input_fee_ppk: self.keyset.input_fee_ppk,
            final_expiry: self.keyset.final_expiry,
            active: self.active,
            keys: self
                .keys()
                .iter()
                .map(|(amount, key)| CashuKey {
                    amount: amount.to_u64(),
                    pubkey: FixedBytes(key.to_bytes()),
                })
                .collect(),
        }
    }

    /// The mint signs the output `(secret, r)` of `amount` and the wallet unblinds it: a proof with
    /// its DLEQ, made by `sign_message`, `BlindSignature::new` and `construct_proofs`.
    pub fn issue(&self, amount: u64, secret: &str, r: &[u8; 32]) -> Proof {
        let r = SecretKey::from_slice(r).expect("valid blinding factor");
        let (blinded, r) = dhke::blind_message(secret.as_bytes(), Some(r)).expect("blinds");
        let keypair = self
            .keyset
            .keys
            .get(&Amount::from(amount))
            .expect("the keyset has this amount");
        let c = dhke::sign_message(&keypair.secret_key, &blinded).expect("signs");
        let signature = BlindSignature::new(
            Amount::from(amount),
            c,
            self.keyset.id,
            &blinded,
            &keypair.secret_key,
        )
        .expect("DLEQ");
        let mut proofs = dhke::construct_proofs(
            vec![signature],
            vec![r],
            vec![Secret::new(secret)],
            &self.keys(),
        )
        .expect("unblinds");
        proofs.pop().expect("one proof")
    }

    /// The mint key for `amount`, as a plain secp256k1 key.
    pub fn mint_key(&self, amount: u64) -> secp256k1::PublicKey {
        *self
            .keyset
            .keys
            .get(&Amount::from(amount))
            .expect("the keyset has this amount")
            .public_key
    }
}

/// A mint: its canonical URL and keysets.
pub struct TestMint {
    pub url: String,
    pub keysets: Vec<TestKeyset>,
}

impl TestMint {
    pub fn descriptor(&self) -> CashuMintDescriptor {
        CashuMintDescriptor {
            url: self.url.clone(),
            unit: "sat".to_owned(),
            keysets: self.keysets.iter().map(TestKeyset::wire).collect(),
        }
    }
}

/// A swap or melt being built: the wire request's inputs and outputs, and the same proofs and
/// blinded messages as the `cashu` crate types them.
#[derive(Default)]
pub struct Spend {
    pub inputs: Vec<CashuInput>,
    pub outputs: Vec<CashuOutput>,
    pub proofs: Vec<Proof>,
    pub blinded: Vec<BlindedMessage>,
}

impl Spend {
    /// A proof of `amount` minted to the wallet's `fps-cashu-v1` output at `(epoch, counter)` of
    /// `keyset`, which is how every proof the wallet spends was made.
    pub fn input(
        &mut self,
        phone: &PhoneMintKeys,
        keyset: &TestKeyset,
        epoch: u32,
        counter: u64,
        amount: u64,
        with_dleq: bool,
    ) {
        let output = phone
            .blinded_output(epoch, &keyset.id_bytes(), counter)
            .expect("derives");
        let proof = keyset.issue(amount, &output.secret, &output.r.secret_bytes());
        self.push_proof(proof, with_dleq);
    }

    /// Spends `proof` as the next input.
    pub fn push_proof(&mut self, proof: Proof, with_dleq: bool) {
        let dleq = proof
            .dleq
            .as_ref()
            .filter(|_| with_dleq)
            .map(|dleq| CashuDleq {
                e: FixedBytes(dleq.e.to_secret_bytes()),
                s: FixedBytes(dleq.s.to_secret_bytes()),
                r: FixedBytes(dleq.r.to_secret_bytes()),
            });
        self.inputs.push(CashuInput {
            amount: proof.amount.to_u64(),
            keyset: ByteBuf(proof.keyset_id.to_bytes()),
            secret: proof.secret.to_string(),
            c: FixedBytes(proof.c.to_bytes()),
            dleq,
        });
        self.proofs.push(proof);
    }

    /// Change: the wallet's output at `(epoch, counter)` of `keyset`, with its hint.
    pub fn change(
        &mut self,
        phone: &PhoneMintKeys,
        keyset: &TestKeyset,
        epoch: u32,
        counter: u64,
        amount: u64,
    ) {
        let output = phone
            .blinded_output(epoch, &keyset.id_bytes(), counter)
            .expect("derives");
        let hint = CashuOutputHint {
            epoch,
            keyset: ByteBuf(keyset.id_bytes()),
            counter,
        };
        self.push_output(
            keyset,
            amount,
            output.secret,
            output.r.secret_bytes(),
            Some(hint),
        );
    }

    /// An output leaving the wallet: a plain secret of 32 random bytes in hex and a random `r`.
    pub fn leaving(&mut self, keyset: &TestKeyset, amount: u64, rng: &mut impl RngCore) {
        let secret = hex::encode(random_bytes(rng));
        let r = random_scalar(rng);
        self.push_output(keyset, amount, secret, r, None);
    }

    /// An output with this opening.
    pub fn push_output(
        &mut self,
        keyset: &TestKeyset,
        amount: u64,
        secret: String,
        r: [u8; 32],
        hint: Option<CashuOutputHint>,
    ) {
        let blinding = SecretKey::from_slice(&r).expect("valid blinding factor");
        let (b, _) = dhke::blind_message(secret.as_bytes(), Some(blinding)).expect("blinds");
        self.blinded
            .push(BlindedMessage::new(Amount::from(amount), keyset.id(), b));
        self.outputs.push(CashuOutput {
            amount,
            keyset: ByteBuf(keyset.id_bytes()),
            b: FixedBytes(b.to_bytes()),
            opening: CashuOpening {
                secret,
                r: FixedBytes(r),
                hint,
            },
        });
    }

    pub fn request(&self, mint: [u8; 32], epoch: u32, kind: CashuSpendKind) -> CashuSignRequest {
        CashuSignRequest {
            mint: FixedBytes(mint),
            epoch,
            inputs: self.inputs.clone(),
            outputs: self.outputs.clone(),
            kind,
        }
    }

    pub fn swap(&self) -> SwapRequest {
        SwapRequest::new(self.proofs.clone(), self.blinded.clone())
    }

    pub fn melt(&self, quote: &str) -> MeltRequest<String> {
        MeltRequest::new(
            quote.to_owned(),
            self.proofs.clone(),
            Some(self.blinded.clone()),
        )
    }
}

/// Puts a `SIG_ALL` signature in the first input's witness, as the phone will.
pub fn attach_signature(inputs: &mut [Proof], signature: &[u8; 64]) {
    let first = inputs.first_mut().expect("at least one input");
    first.witness = Some(Witness::P2PKWitness(P2PKWitness {
        signatures: vec![hex::encode(signature)],
    }));
}

/// The swap with `signature` attached passes `verify_spending_conditions`, the check a CDK mint
/// runs.
pub fn swap_accepts(swap: &SwapRequest, signature: &[u8; 64]) -> bool {
    let mut swap = swap.clone();
    attach_signature(swap.inputs_mut(), signature);
    swap.verify_spending_conditions().is_ok()
}

/// The melt with `signature` attached passes `verify_spending_conditions`.
pub fn melt_accepts(melt: &MeltRequest<String>, signature: &[u8; 64]) -> bool {
    let mut melt = melt.clone();
    attach_signature(melt.inputs_mut(), signature);
    melt.verify_spending_conditions().is_ok()
}

/// A signed BOLT11 invoice from a fixed node key, valid for the device's parser.
pub fn invoice(amount_msat: u64, description: &str, payment_hash: [u8; 32]) -> String {
    use bitcoin::hashes::{sha256, Hash};
    let node = secp256k1::SecretKey::from_slice(&[0x77; 32]).expect("valid key");
    let secp = Secp256k1::new();
    lightning_invoice::InvoiceBuilder::new(lightning_invoice::Currency::Bitcoin)
        .description(description.to_owned())
        .payment_hash(sha256::Hash::from_byte_array(payment_hash))
        .payment_secret(lightning_invoice::PaymentSecret([3; 32]))
        .duration_since_epoch(std::time::Duration::from_secs(1_800_000_000))
        .min_final_cltv_expiry_delta(144)
        .amount_milli_satoshis(amount_msat)
        .build_signed(|hash| secp.sign_ecdsa_recoverable(hash, &node))
        .expect("signs")
        .to_string()
}

pub fn random_bytes(rng: &mut impl RngCore) -> [u8; 32] {
    let mut bytes = [0u8; 32];
    rng.fill_bytes(&mut bytes);
    bytes
}

/// A uniformly random valid scalar.
pub fn random_scalar(rng: &mut impl RngCore) -> [u8; 32] {
    loop {
        let bytes = random_bytes(rng);
        if secp256k1::SecretKey::from_slice(&bytes).is_ok() {
            return bytes;
        }
    }
}

/// A random point with a known discrete log.
pub fn random_point(rng: &mut impl RngCore) -> PublicKey {
    SecretKey::from_slice(&random_scalar(rng))
        .expect("valid scalar")
        .public_key()
}

/// The key `x·G` for a small scalar, as the collision demos use.
pub fn point_of(scalar: u64) -> secp256k1::PublicKey {
    let mut bytes = [0u8; 32];
    bytes[24..].copy_from_slice(&scalar.to_be_bytes());
    let secret = secp256k1::SecretKey::from_slice(&bytes).expect("valid scalar");
    secp256k1::PublicKey::from_secret_key(&Secp256k1::new(), &secret)
}

/// Whether `text` is a compressed point in lowercase hex.
pub fn is_point_hex(text: &str) -> bool {
    hex::decode(text)
        .ok()
        .is_some_and(|bytes| secp256k1::PublicKey::from_slice(&bytes).is_ok())
}
